"""Feature list (as openscad_to_ckpart.py builds it) -> CivilKit script text (`@kit/script`, docs/scripting.md).

The script is the source: run in the app's Script tab (or run_script.mjs) it records the same history, the document keeps it in its
`script` field, and editing it regenerates the part. Sketches are `sketchFeature`, booleans are `combine`, everything else is a raw
`feature({...})` with the kernel's own field names; the document's variables become `variables({...})`, per-feature colours `appearance`.
"""
import json, re


def _num(x):
    try: return float(x)
    except Exception: return None


def _js(o):
    return json.dumps(o, separators=(", ", ": ")).replace('"', "'") if False else json.dumps(o, separators=(", ", ": "))


def _r(x): return round(float(x), 7) + 0.0


def _builder_sketch(g):
    """closed polygons and circles only (no arcs, axis, constraints) -> `s.polygon(...)` / `s.circle(...)` calls, else None"""
    ents = g["entities"]
    if g.get("constraints") or any(e["type"] not in ("line", "circle") or e["id"] == "ax" for e in ents): return None
    P = {p["id"]: p for p in g["points"]}
    parts = []
    for e in ents:
        if e["type"] == "circle":
            c = P[e["c"]]; parts.append(f"s.circle({_r(e['r']):g}, [{_r(c['x']):g}, {_r(c['y']):g}]);")
    nxt = {}
    for e in ents:
        if e["type"] == "line":
            if e["p1"] in nxt: return None
            nxt[e["p1"]] = e["p2"]
    seen = set()
    for st in list(nxt):
        if st in seen: continue
        ch = [st]; cur = nxt[st]
        while cur != st:
            if cur not in nxt or cur in ch: return None
            ch.append(cur); cur = nxt[cur]
        seen.update(ch)
        parts.append("s.polygon([" + ", ".join(f"[{_r(P[i]['x']):g}, {_r(P[i]['y']):g}]" for i in ch) + "]);")
    return " " + " ".join(parts) + " " if parts else None


def decompile(doc, source_note=""):
    feats = doc["features"]; name = doc.get("name", "part").split("__")[-1]
    ids = {f["id"] for f in feats}
    L = []
    if source_note: L.append(f"// {source_note}")
    L.append("// Generated by openscad_to_ckpart.py. Edit freely: running this script rebuilds the feature history.")
    vs = doc.get("variables") or []
    if vs:
        items = []
        for v in vs:
            n = _num(v["expr"]); items.append(f"{v['name']}: {n:g}" if n is not None else f"{v['name']}: {json.dumps(v['expr'])}")
        L.append("variables({ " + ", ".join(items) + " });")
    grp = feats[0].get("group") if feats else None
    body = []
    last_sketch = None
    order = []   # script feature index -> original id (the recorder numbers its own features F1, F2, ... in the same order)
    for f in feats:
        t = f["type"]
        g = {k: v for k, v in f.items() if k not in ("id", "name", "group")}
        if t == "sketch":
            plane = g["plane"]
            on = plane["id"] if isinstance(plane, dict) and plane.get("kind") == "std" else None
            if on is None: raise ValueError("non-standard sketch plane")
            pretty = _builder_sketch(g)
            if pretty is not None:
                body.append(f"  .sketch('{on}', (s) => {{{pretty}}})")
                last_sketch = f["id"]; order.append(f["id"]); continue
            used = {"O"} | {v for e in g["entities"] for k, v in e.items() if k in ("p1", "p2", "c") and isinstance(v, str)}
            sk = {"points": [p for p in g["points"] if p["id"] in used], "entities": g["entities"]}
            if g.get("constraints"): sk["constraints"] = g["constraints"]
            body.append(f"  .sketchFeature('{on}', {_js(sk)})")
            last_sketch = f["id"]
        elif t == "combine" and g.get("op") in ("union", "cut", "intersect") and not g.get("keepTools") and "body" in (g.get("target") or {}):
            tools = [x["body"] for x in g["tools"]]
            body.append(f"  .combine('{g['op']}', {json.dumps(g['target']['body'])}, {json.dumps(tools)})")
        else:
            if g.get("sketch") == last_sketch: g["sketch"] = "$sketch"
            elif g.get("sketch") in ids: raise ValueError(f"{t} refers to an earlier sketch {g['sketch']}")
            body.append(f"  .feature({_js(g)})")
        order.append(f["id"])
    # colours: the recorder numbers features F1.. in order, so the original ids still hold
    ap = doc.get("appearance") or {}
    renum = {old: f"F{i + 1}" for i, old in enumerate(order)}
    for fid, a in ap.items():
        if fid in renum: body.append(f"  .appearance({{ feature: '{renum[fid]}', colour: '{a['color']}' }})")
    head = "part(" + json.dumps(name) + ")"
    chain = "\n".join([head] + body)
    if grp:   # the part must exist before group(); the folder is the part's name
        chain = "const p = " + head + ";\ngroup(" + json.dumps(grp) + ", () => {\n  p\n" + "\n".join("  " + b for b in body) + ";\n});"
    else: chain += ";"
    text = "\n".join(L) + "\n" + chain + "\n"
    return text
